#!/usr/bin/env python3
"""P10 mechanical guide assembly. Generates the ledger-derived, manifest-derived parts of
guide/ and drops <NARRATIVE> skeletons for the judgment layers. Rerunnable: regenerated
sections are overwritten; narrative belongs in the specs, never hand-edit the guide.

Usage: render_guide.py [--root ROOT]
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rk_common import die, find_root, load_layout

sys.path.insert(0, str(Path(__file__).parent))
from replay import load_yaml  # mini-YAML reader

GENERATED = ("<!-- GENERATED by rebuild-kit render_guide.py — never hand-edit; "
             "corrections belong in the specs, then re-render. -->\n\n")


def wo_stats(root):
    stats = []
    for f in sorted((root / "docs" / "features").glob("WO-*.md")):
        text = f.read_text(errors="replace")
        tags = {t: len(re.findall(rf"fidelity:\s*{t}", text)) for t in
                ("FIXED", "REPAIR", "FREE", "ASK")}
        title = text.splitlines()[0].lstrip("# ") if text.splitlines() else f.stem
        stats.append({"file": f.name, "title": title, **tags})
    return stats


def render_decisions(root):
    lines = ["# Decisions — the rewrite's readable changelog", ""]
    div_path = root / "verification" / "replay" / "expected-divergences.yaml"
    if div_path.exists():
        divs = load_yaml(div_path) or []
        lines += ["## Sanctioned behavior changes (expected-divergence manifest)", "",
                  "| ID | PB | WO | was | becomes | ruled by |", "|---|---|---|---|---|---|"]
        for d in divs if isinstance(divs, list) else []:
            lines.append(f"| {d.get('id')} | {d.get('pb')} | {d.get('wo')} | "
                         f"{d.get('legacy')} | {d.get('expected')} | {d.get('ruled_by', 'UNSIGNED')} |")
        lines.append("")
    oq = root / "docs" / "open-questions.md"
    if oq.exists():
        text = oq.read_text(errors="replace")
        ruled = re.findall(r"##\s*(OQ-\d+)[^\n]*\n(?:(?!##).)*?ruling:(?![ \t]*PENDING)[ \t]*([^\n]+)",
                           text, re.DOTALL)
        pending = re.findall(r"##\s*(OQ-\d+)([^\n]*)\n(?:(?!##).)*?ruling:\s*PENDING",
                             text, re.DOTALL)
        lines += ["## Rulings", ""]
        lines += [f"- **{oid}** — {r.strip()}" for oid, r in ruled] or ["(none yet)"]
        lines += ["", "## Still open", ""]
        lines += [f"- **{oid}**{t}" for oid, t in pending] or ["(none)"]
    return "\n".join(lines) + "\n"


def render_then_vs_now(root, stats):
    lines = ["# Then vs Now — the rewrite at a glance", "",
             "Per work order: what changes (REPAIR, traced to PB), what holds (FIXED), "
             "what's still undecided (ASK).", "",
             "| work order | holds (FIXED) | changes (REPAIR) | open (ASK) | free choices |",
             "|---|---|---|---|---|"]
    for s in stats:
        lines.append(f"| {s['title']} (`{s['file']}`) | {s['FIXED']} | {s['REPAIR']} | "
                     f"{s['ASK']} | {s['FREE']} |")
    lines += ["", "<NARRATIVE: per-subsystem prose — what a user of the old system will "
              "notice, what they won't, citing ED-*/PB-* entries.>"]
    return "\n".join(lines) + "\n"


def render_orientation(root, cfg, stats):
    ledger = json.loads((root / "ledger.json").read_text()) if (root / "ledger.json").exists() else {}
    lines = ["# Orientation — the 10-minute tour", "",
             "<NARRATIVE: what this system is, in three sentences, for a new arrival.>", "",
             f"- Legacy pinned at `{cfg['legacy_ref'][:12]}` ({cfg['legacy_pin_method']})",
             f"- Evidence subsystems: " + ", ".join(
                 f"{k}={v}" for k, v in cfg.get("evidence", {}).items() if k != "notes"),
             "", "## Where to start",
             "1. `legacy/` chapters here in the guide — how the current system works",
             "2. `then-vs-now.md` — what the rewrite changes and why",
             "3. `decisions.md` — every sanctioned deviation, with rulings", "",
             "## Execution state", ""]
    ms = ledger.get("milestones", [])
    if ms:
        lines += ["| milestone | status | gate | approved |", "|---|---|---|---|"]
        lines += [f"| {m.get('id')} {m.get('name', '')} | {m.get('status')} | "
                  f"{'yes' if m.get('gate') else '—'} | {m.get('approved_by') or '—'} |"
                  for m in ms]
    else:
        lines.append("(ledger has no milestones yet — generated before P8?)")
    lines += ["", f"Work orders: {len(stats)} · audit metrics: "
              f"{json.dumps(ledger.get('audit', {}))}"]
    return "\n".join(lines) + "\n"


def subsystems(root):
    ov = root / "docs" / "00-overview.md"
    if not ov.exists():
        return []
    rows = re.findall(r"^\|([^|\n]+)\|", ov.read_text(errors="replace"), re.MULTILINE)
    return [r.strip() for r in rows[2:] if r.strip() and not set(r.strip()) <= {"-", " "}]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root")
    args = ap.parse_args()
    root = Path(args.root).resolve() if args.root else find_root()
    if not root:
        die("no rebuild.json found")
    cfg, _, _ = load_layout(root)

    guide = root / "guide"
    for d in ("legacy", "modern", "flows", "briefs"):
        (guide / d).mkdir(parents=True, exist_ok=True)

    stats = wo_stats(root)
    (guide / "decisions.md").write_text(GENERATED + render_decisions(root))
    (guide / "then-vs-now.md").write_text(GENERATED + render_then_vs_now(root, stats))
    (guide / "00-orientation.md").write_text(GENERATED + render_orientation(root, cfg, stats))

    gl_src = root / "docs" / "domain" / "glossary.md"
    if gl_src.exists():
        (guide / "glossary.md").write_text(GENERATED + gl_src.read_text())

    made = []
    for name in subsystems(root):
        slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
        for side, note in (("legacy", "how it works today"), ("modern", "designed-not-built")):
            p = guide / side / f"{slug}.md"
            if not p.exists():  # chapters keep narrative once written — skeleton only if absent
                p.write_text(f"# {name} ({note})\n\n<NARRATIVE: see "
                             f"phases/P10-field-guide.md — cite the audited specs.>\n")
                made.append(str(p.relative_to(root)))

    print(json.dumps({"generated": ["guide/decisions.md", "guide/then-vs-now.md",
                                    "guide/00-orientation.md"],
                      "chapter_skeletons_created": made,
                      "work_orders_seen": len(stats)}, indent=2))
    print("\nNext: write narrative layers on the skeletons (legacy chapters, flow storyboards "
          "from the replay corpus); honesty rules apply — nothing beyond the audited spec.")


if __name__ == "__main__":
    main()
